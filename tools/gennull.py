#!/usr/bin/env python3
"""gennull.py <BaseClass> <header relative to GameEngine/Include or GameEngineDevice/Include> [NullName]
Uses clang's JSON AST dump to find every pure virtual of BaseClass (and of its abstract bases) and emits
src/null/<NullName>.h and .cpp: a concrete subclass whose overrides do nothing and return value-initialised results."""
import json,subprocess,sys,re,os,shlex
R='/home/dnlwtsn/Code/zh-living-world'
bases=sys.argv[1].split(','); hdrs=sys.argv[2].split(','); base=bases[0]; hdr=hdrs[0]; null=sys.argv[3] if len(sys.argv)>3 else 'Null'+base
cc=json.load(open(R+'/build/cm/compile_commands.json'))
e=[c for c in cc if c['file'].endswith('stubs_manual.cpp')][0]
a=shlex.split(e['command']); i=a.index('-o'); a=a[:i]+['-fsyntax-only']+a[i+2:]
for k in ('-MT','-MF'):
    while k in a: j=a.index(k); del a[j:j+2]
a=[x for x in a if x not in('-MD',)]
a=[x for x in a if not x.endswith('stubs_manual.cpp')]
tu=R+'/build/gennull_tu.cpp'
open(tu,'w').write('#include "PreRTS.h"\n'+''.join('#include "%s"\n'%h for h in hdrs)+'class UMProbe : public %s {};\n'%', public '.join(bases))
txt=''
for b in bases:
    r=subprocess.run(a+['-Xclang','-ast-dump=json','-Xclang','-ast-dump-filter='+b,tu],capture_output=True,text=True,cwd=e['directory'])
    txt+=r.stdout
# the output is a sequence of JSON objects (one per matched decl); split them
dec=json.JSONDecoder(); pos=0; nodes=[]
while pos<len(txt):
    while pos<len(txt) and txt[pos] in ' \n\r\t': pos+=1
    if pos>=len(txt): break
    o,end=dec.raw_decode(txt,pos); nodes.append(o); pos=end
def walk(n):
    yield n
    for c in n.get('inner',[]) or []: yield from walk(c)
meths=[];seen=set()
for n in nodes:
    for m in walk(n):
        if m.get('kind')=='CXXRecordDecl' and m.get('name') in bases and m.get('completeDefinition'):
            for c in m.get('inner',[]):
                if c.get('kind')=='CXXMethodDecl' and c.get('pure'):
                    meths.append(c)
if not meths: print('no pure virtuals found for',base,r.stderr[:300]); sys.exit(1)
def split_type(q):
    # "RET (A, B) const" -> RET, const
    depth=0; start=None
    for i,ch in enumerate(q):
        if ch=='(' and depth==0 and start is None: start=i
        if ch=='(': depth+=1
        if ch==')':
            depth-=1
            if depth==0 and start is not None: end=i; break
    ret=q[:start].strip(); tail=q[end+1:].strip()
    return ret,tail
hd=['// GENERATED by tools/gennull.py: inert implementation of %s for the dedicated-server build.'%base,'#pragma once','#include "PreRTS.h"',''.join('#include "%s"\n'%h for h in hdrs),'class %s : public %s\n{\npublic:'%(null,', public '.join(bases))]
cp=['// GENERATED by tools/gennull.py','#include "null/%s.h"'%null]
for m in meths:
    ret,tail=split_type(m['type']['qualType'])
    ps=[]
    for p in m.get('inner',[]):
        if p.get('kind')=='ParmVarDecl':
            ps.append((p['type']['qualType'],p.get('name','')))
    def decl(ps): 
        out=[]
        for k,(t,n) in enumerate(ps):
            n=n or 'a%d'%k
            mm=re.match(r'^(.*?)(\[.*\])$',t)
            if mm: out.append('%s %s%s'%(mm.group(1),n,mm.group(2)))
            elif '(*)' in t: out.append(t.replace('(*)','(*%s)'%n,1))
            else: out.append('%s %s'%(t,n))
        return ', '.join(out)
    args=decl(ps); const=' const' if 'const' in tail else ''
    name=m['name']
    hd.append('\tvirtual %s %s(%s)%s;'%(ret,name,args,const))
    body=''
    if ret!='void':
        if ret.endswith('&'):
            bare=re.sub(r'^const\s+','',ret[:-1].strip())
            body=' static %s s_d; return s_d;'%bare
        else: body=' typedef %s UMRet; return UMRet();'%ret
    cp.append('%s %s::%s(%s)%s {%s }'%(ret,null,name,args,const,body))
if len(sys.argv)>5:
    hd.insert([k for k,x in enumerate(hd) if x.startswith('class ')][0]+1,'\t%s(%s) : %s {}'%(null,sys.argv[4],sys.argv[5]))
hd.append('};\n')
os.makedirs(R+'/src/null',exist_ok=True)
open(R+'/src/null/%s.h'%null,'w').write('\n'.join(hd))
open(R+'/src/null/%s.cpp'%null,'w').write('\n'.join(cp)+'\n')
print(null,len(meths),'methods')
