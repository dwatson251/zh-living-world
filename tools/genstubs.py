#!/usr/bin/env python3
"""Generate src/stubs_gen.cpp: inert definitions for menu/GameSpy callbacks the headless build links but never calls.
Reads build/undef.txt (lld's demangled 'undefined symbol' list). Only handles the uniform GUI-callback signatures."""
import re
R='/home/dnlwtsn/Code/zh-living-world'
syms=[l.strip() for l in open(R+'/build/undef.txt')]
out=['// GENERATED by tools/genstubs.py: stubs for removed UI/online callbacks (headless server never invokes them).',
     '#include "PreRTS.h"','#include "GameClient/GameWindow.h"','#include "GameClient/WindowLayout.h"','']
other=[]
for s in syms:
    m=re.match(r'^(\w+)\(WindowLayout\*, void\*\)$',s)
    if m: out.append('void %s(WindowLayout*, void*) {}'%m.group(1)); continue
    m=re.match(r'^(\w+)\(GameWindow\*, unsigned int, unsigned int, unsigned int\)$',s)
    if m:
        out.append('%s %s(GameWindow*, UnsignedInt, UnsignedInt, UnsignedInt) { return MSG_IGNORED; }'%('WindowMsgHandledType' if re.search(r'(Input)$',m.group(1)) else 'WindowMsgHandledType',m.group(1))); continue
    other.append(s)
import os
prev=[]
if os.path.exists(R+'/src/stubs_gen.cpp'):
    prev=[l for l in open(R+'/src/stubs_gen.cpp').read().split('\n') if l.startswith(('void ','WindowMsgHandledType '))]
body=sorted(set(prev)|set(l for l in out if l.startswith(('void ','WindowMsgHandledType '))))
hdr=[l for l in out if not l.startswith(('void ','WindowMsgHandledType '))]
open(R+'/src/stubs_gen.cpp','w').write('\n'.join(hdr+body)+'\n')
open(R+'/build/undef_other.txt','w').write('\n'.join(other)+'\n')
print(len(syms)-len(other),'stubbed;',len(other),'left')
