#!/usr/bin/env python3
"""gend3d.py: read mingw's d3d8.h and write src/client/d3dnull/gen_d3d8.h: for every Direct3D 8 interface a class `Gen<Interface>` implementing every method as an inert
default (S_OK / 0 / FALSE / void). The hand-written null device (null_d3d8.cpp) derives from these and overrides only what the engine needs."""
import re
H = open('/home/dnlwtsn/tools/llvm-mingw-20261006/i686-w64-mingw32/include/d3d8.h').read()
out = ['// GENERATED by tools/gend3d.py from d3d8.h: inert default implementations of the Direct3D 8 interfaces (the server renders to nothing).', '#pragma once', '#include <windows.h>', '#include <d3d8.h>', '']
ifaces = re.finditer(r'DECLARE_INTERFACE_IID_\((\w+),(\w+),"[^"]*"\)\s*\{(.*?)\n\};', H, re.S)
for m in ifaces:
    name, base, body = m.group(1), m.group(2), m.group(3)
    out.append('class Gen%s : public %s\n{\npublic:' % (name, name))
    for d in re.finditer(r'STDMETHOD(_?)\((.*?)\)\s*\((.*?)\)\s*PURE;', body, re.S):
        ret_given, head, params = d.group(1), d.group(2), d.group(3)
        if ret_given:
            ret, meth = [x.strip() for x in head.split(',', 1)]
        else:
            ret, meth = 'HRESULT', head.strip()
        params = re.sub(r'\s+', ' ', params.strip())
        params = re.sub(r'^THIS_\s*', '', params); params = '' if params == 'THIS' else params
        if meth in ('QueryInterface', 'AddRef', 'Release'):
            continue            # the concrete classes implement the IUnknown part
        body_ret = 'return D3D_OK;' if ret == 'HRESULT' else ('return (%s)0;' % ret if ret != 'void' else '')
        out.append('\tvirtual %s STDMETHODCALLTYPE %s(%s) { %s }' % (ret, meth, params, body_ret))
    out.append('};\n')
open('/home/dnlwtsn/Code/zh-living-world/src/client/d3dnull/gen_d3d8.h', 'w').write('\n'.join(out))
print(len(out), 'lines')
